"""Generate manuscript tables (Markdown) from result files."""
import json, glob, pickle, numpy as np
E = json.load(open('results/denovo_eval_ev.json'))
abl = {k: json.load(open(f'results/denovo_eval_{k}.json'))['inDB']['SpecNovo'] for k in ('base', 'ma', 'ev400', 'ev800')}
S = json.load(open('results/denovo_summary.json'))
D = pickle.load(open('data/ms2_corpus.pkl', 'rb'))
out = []
POBS = '*p*~obs~'
f3 = lambda x: f'{x:.3f}'
# Table 1
t = ['| Corpus / set | Source | Spectra | Unique peptides | Condition |', '|---|---|---|---|---|',
     f"| Training | proteome T (3,000 proteins) | 250,000 | {D['n_pep']['T']:,} | {POBS} ∼ U(0.55, 0.95), λ ∼ U(10, 100) |",
     f"| Validation | proteome T | 2,000 | – | {POBS} = 0.80, λ = 40 |"]
for k, src, cond in [('inDB', 'proteome P (in database)', '*p*~obs~ = 0.80, λ = 40'), ('SAAV', 'P + single AA variant', '*p*~obs~ = 0.80, λ = 40'),
                     ('novel', 'proteome N (not in DB)', '*p*~obs~ = 0.80, λ = 40')]:
    t.append(f"| {k} | {src} | {len(D['tests'][k]):,} | {len(set(x[4] for x in D['tests'][k])):,} | {cond} |")
t.append("| Robustness ×8 | proteome P | 8 × 1,000 | – | *p*~obs~ ∈ {0.95, 0.80, 0.65, 0.50}; λ ∈ {10,40,100,200} |")
t.append(f"| Search database | proteome P targets (+Met-ox) | – | {len(D['db']):,} | + equal number of reversed decoys |")
t.append("| MS1 cohorts | 300 features, 4 sites | 800 unlabeled + 384 labelled + 500 test runs / seed | – | 20 biomarkers, absolute log₂FC 0.26–0.44 |")
out.append(('Table 1. Benchmark corpora generated by the virtual instrument.', t))
# Table 3 main de novo
t = ['| Test set | Method | AA precision | AA recall | Peptide recall | PR-AUC | False IDs (1 % FDR) |', '|---|---|---|---|---|---|---|']
for s in ('inDB', 'SAAV', 'novel'):
    for m in ('DB-search', 'SpectrumGraph-DP', 'SpecNovo'):
        r = E[s][m]
        if m == 'DB-search':
            t.append(f"| {s} | {m} | – | – | {f3(r['peptide_recall'])} | – | {f3(r['false_ids'])} |")
        else:
            t.append(f"| {s} | {m} | {f3(r['aa_precision'])} | {f3(r['aa_recall'])} | {f3(r['peptide_recall'])} | {f3(r['pr_auc'])} | – |")
out.append(('Table 3. Database-dependent and database-free peptide identification.', t))
# Table 4 robustness
t = ['| Condition | DB-search pep. recall | SpectrumGraph-DP pep. recall | SpecNovo pep. recall | DP AA prec. | SpecNovo AA prec. | DP PR-AUC | SpecNovo PR-AUC |', '|---|---|---|---|---|---|---|---|']
for k in ['pobs_0.95', 'pobs_0.80', 'pobs_0.65', 'pobs_0.50', 'noise_10', 'noise_40', 'noise_100', 'noise_200']:
    r = E[k]; lab = k.replace('pobs_', '*p*~obs~ = ').replace('noise_', 'λ = ')
    t.append(f"| {lab} | {f3(r['DB-search']['peptide_recall'])} | {f3(r['SpectrumGraph-DP']['peptide_recall'])} | {f3(r['SpecNovo']['peptide_recall'])} | "
             f"{f3(r['SpectrumGraph-DP']['aa_precision'])} | {f3(r['SpecNovo']['aa_precision'])} | {f3(r['SpectrumGraph-DP']['pr_auc'])} | {f3(r['SpecNovo']['pr_auc'])} |")
out.append(('Table 4. Robustness to fragment completeness and chemical noise (1,000 spectra per condition).', t))
# Table 5 ablation
logs = {k: json.load(open(f'results/trainlog_{k}.json')) for k in ('main', 'ma', 'ev')}
def acc_at(k, step): return [r['val_tok_acc'] for r in logs[k] if r['step'] == step][0]
t = ['| Variant | Training spectra | Val. token acc. (TF) | AA precision | AA recall | Peptide recall | PR-AUC |', '|---|---|---|---|---|---|---|']
rows = [('Base transformer', '448k', acc_at('main', 3500), abl['base']), ('+ complementary ions & prefix-mass decoding', '256k', acc_at('ma', 2000), abl['ma']),
        ('+ ion-evidence term (+400 steps)', '307k', acc_at('ev', 400), abl['ev400']), ('+ ion-evidence term (+800 steps)', '358k', acc_at('ev', 800), abl['ev800']),
        ('+ ion-evidence term (+1,200 steps, final)', '410k', acc_at('ev', 1200), E['inDB']['SpecNovo'])]
for n, sp, a, r in rows:
    t.append(f"| {n} | {sp} | {f3(a)} | {f3(r['aa_precision'])} | {f3(r['aa_recall'])} | {f3(r['peptide_recall'])} | {f3(r['pr_auc'])} |")
out.append(('Table 5. Ablation of SpecNovo inductive biases on the inDB test set (beam K = 5).', t))
# Table 8 representation
t = ['| Analysis | Metric | Value |', '|---|---|---|',
     f"| Replicate retrieval (40 peptides × 12 spectra) | top-1 accuracy, encoder embedding | {f3(S['retrieval_top1_encoder'])} |",
     f"| | top-1 accuracy, binned spectrum (0.5 Da) | {f3(S['retrieval_top1_binned'])} |",
     f"| | silhouette (cosine), encoder | {f3(S['silhouette_encoder'])} |",
     f"| | silhouette (cosine), binned | {f3(S['silhouette_binned'])} |",
     f"| Peak attribution (300 inDB spectra) | mean saliency share on annotated fragment ions | {f3(S['saliency_on_fragments_mean'])} |",
     f"| | mean intensity share on annotated fragment ions | {f3(S['intensity_on_fragments_mean'])} |",
     f"| Inference cost | CPU seconds per 1,000 spectra (beam K=5, 2 threads) | {E['inDB']['SpecNovo']['secs_per_1k']:.0f} |"]
P = json.load(open('results/pheno_summary.json'))
t += [f"| Feature attribution (seed 0, n = 384) | AUROC of abs(grad × input) for true biomarkers | {f3(P['attr_auroc'])} |",
      f"| | AUROC of Welch t-test −log10 p (ID-free matrix) | {f3(P['ttest_auroc'])} |"]
out.append(('Table 8. Representation quality, interpretability and compute.', t))
# Table 6 phenotype
names = ['ID-first-LR', 'ID-first+MBR-LR', 'ID-free-LR', 'FeatureFormer', 'FeatureFormer+SSL']
t = ['| Method | n = 24 | n = 48 | n = 96 | n = 192 | n = 384 | LOSO (unseen site) |', '|---|---|---|---|---|---|---|']
for m in names:
    cells = [f"{P[m][str(n)][0]:.3f} ± {P[m][str(n)][1]:.3f}" for n in (24, 48, 96, 192, 384)]
    cells.append(f"{P['LOSO'][m][0]:.3f} ± {P['LOSO'][m][1]:.3f}")
    t.append(f"| {m} | " + ' | '.join(cells) + ' |')
out.append(('Table 6. Spectrum-to-phenotype AUROC (mean ± s.d. over three seeds; 500 test runs; 50 % of biomarkers unidentifiable).', t))
t = ['| Method | 0 % | 25 % | 50 % | 75 % |', '|---|---|---|---|---|']
for m, v in P['sweep'].items():
    t.append(f"| {m} | " + ' | '.join(f"{x[0]:.3f} ± {x[1]:.3f}" for x in v) + ' |')
out.append(('Table 7. AUROC (n = 192) as a function of the fraction of biomarkers that are not identifiable by MS2 database search.', t))
order = [0, 1, 2, 3, 5, 6, 4]
out = [out[i] for i in order]
import re
with open('paper/tables.md', 'w') as f:
    for cap, t in out:
        f.write(f'**{cap}**\n\n' + '\n'.join(t) + '\n\n')
print(open('paper/tables.md').read())
